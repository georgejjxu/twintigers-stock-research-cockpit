package ca.twintigers.research.cli;

import ca.twintigers.research.adapters.Wiring;
import ca.twintigers.research.application.RuleTuner;
import ca.twintigers.research.domain.market.Bar;
import ca.twintigers.research.domain.market.MarketContext;
import ca.twintigers.research.domain.market.PriceRules;
import ca.twintigers.research.domain.portfolio.Portfolio;

import java.io.PrintStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.LocalDate;
import java.time.temporal.ChronoUnit;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;

/**
 * {@code tune-rules [--years 5] [--min-hit 55] [--min-is 15] [--min-oos 8] [--out FILE] [--write-config]}: runs
 * {@link RuleTuner} on the holdings' history and writes the report; with --write-config, replaces the generated block
 * in java/config/rules.properties.
 */
final class TuneRules {

    static final String BEGIN = "# >>> generated by `research-cli tune-rules`; do not edit by hand inside this block";
    static final String END = "# <<< end of generated block";

    private TuneRules() {
    }

    static int run(Wiring w, CliMain.Args a, PrintStream out) throws Exception {
        int years = a.intOpt("--years", 5);
        RuleTuner tuner = new RuleTuner(a.doubleOpt("--min-hit", 55), a.intOpt("--min-is", 15), a.intOpt("--min-oos", 8));
        LocalDate today = LocalDate.now(w.clock);
        List<MarketContext> contexts = new ArrayList<>();
        List<String> symbols = w.portfolio.portfolio().positions().stream().map(Portfolio.Position::symbol).toList();
        for (String s : symbols) {
            List<Bar> bars = w.prices.market().dailyBars(s, today.minusYears(years).minusDays(60), today);
            if (!bars.isEmpty() && bars.getLast().date().equals(today)) {
                bars = bars.subList(0, bars.size() - 1); // only completed sessions
            }
            contexts.add(new MarketContext(s, bars, w.priceConfig));
        }
        LocalDate first = contexts.stream().map(c -> c.bar(0).date()).min(LocalDate::compareTo).orElseThrow();
        LocalDate split = first.plusDays(ChronoUnit.DAYS.between(first, today) / 2);
        RuleTuner.Report r = tuner.tune(contexts, PriceRules.all(w.priceConfig), split);
        String md = markdown(r, symbols);
        String outFile = a.opt("--out");
        if (outFile != null) {
            Path f = Path.of(outFile);
            if (f.getParent() != null) {
                Files.createDirectories(f.getParent());
            }
            Files.writeString(f, md, StandardCharsets.UTF_8);
            out.println("Wrote " + f.toAbsolutePath());
        } else {
            out.println(md);
        }
        List<String> lines = RuleTuner.configLines(r);
        if (a.flag("--write-config")) {
            Path rules = Path.of(w.settings.get("RESEARCH_RULES_FILE", "java/config/rules.properties"));
            writeBlock(rules, lines, today);
            out.println("Updated " + rules.toAbsolutePath() + " (" + lines.size() + " lines).");
        }
        r.decisions().forEach(d -> out.println((d.keep() ? "KEEP   " : "DEMOTE ") + d.ruleId() + " — " + d.reason()));
        return 0;
    }

    static void writeBlock(Path rules, List<String> lines, LocalDate date) throws Exception {
        String text = Files.exists(rules) ? Files.readString(rules, StandardCharsets.UTF_8) : "";
        int b = text.indexOf(BEGIN);
        int e = text.indexOf(END);
        if (b >= 0 && e > b) {
            text = text.substring(0, b) + text.substring(e + END.length()).replaceFirst("^\\R", "");
        }
        StringBuilder block = new StringBuilder(BEGIN).append('\n').append("# Tuned ").append(date)
                .append(" on the holdings' history; report: docs/alerts/rule-tuning.md\n");
        lines.forEach(l -> block.append(l).append('\n'));
        block.append(END).append('\n');
        if (!text.isEmpty() && !text.endsWith("\n")) {
            text += "\n";
        }
        Files.writeString(rules, text + "\n" + block, StandardCharsets.UTF_8);
    }

    static String pct(Double v) {
        return v == null ? "–" : String.format(Locale.ROOT, "%.1f", v);
    }

    static String row(RuleTuner.Stats s) {
        return s.n() + " | " + pct(s.hit5()) + " | " + pct(s.hit20());
    }

    static String markdown(RuleTuner.Report r, List<String> symbols) {
        StringBuilder b = new StringBuilder("# Price-rule tuning: which signals are trustworthy on these stocks\n\n");
        b.append("Generated ").append(LocalDate.now()).append(" by `research-cli tune-rules`. History ").append(r.from()).append(" to ")
         .append(r.to()).append(" for ").append(String.join(", ", symbols)).append(".\n\n");
        b.append("**Method (guarding against overfitting).** Each warning and watch rule with a direction was tried in a small fixed set of stricter versions ")
         .append("(no parameter search). The best version was chosen on the **in-sample** period (")
         .append(r.from()).append(" to ").append(r.split().minusDays(1)).append(") only, then checked on the **out-of-sample** period (")
         .append(r.split()).append(" to ").append(r.to()).append(") it had not seen. A rule stays a *warning* only if that version went the ")
         .append("rule's way at least ").append((int) r.minHit()).append("% of the time at both 5 and 20 trading days, with at least ")
         .append(r.minInSample()).append(" cases in-sample and ").append(r.minOutOfSample()).append(" out-of-sample. All other such rules ")
         .append("are demoted to *info*: still shown in the Cockpit and by `price_signals`, but not as warnings and not pushed by the monitor.\n\n");
        b.append("**Base rate** (how often these stocks simply closed lower after 5 / 20 days, any day):\n\n| Period | Days | Down after 5 d % | Down after 20 d % |\n|---|---:|---:|---:|\n");
        r.baseRates().forEach(x -> b.append("| ").append(x.period()).append(" | ").append(x.n()).append(" | ").append(pct(x.down5()))
                .append(" | ").append(pct(x.down20())).append(" |\n"));
        b.append("\nA bearish rule at 50% is only slightly better than this base rate; the 55% bar asks for a clear edge.\n\n");
        b.append("## Before and after\n\nHit % = share of cases where the close 5 / 20 trading days later went the rule's way.\n\n")
         .append("| Rule | Before: in-sample cases | 5 d % | 20 d % | Before: out-of-sample cases | 5 d % | 20 d % | Chosen version | After: in-sample cases | 5 d % | 20 d % | After: out-of-sample cases | 5 d % | 20 d % | Decision |\n")
         .append("|---|---:|---:|---:|---:|---:|---:|---|---:|---:|---:|---:|---:|---:|---|\n");
        for (RuleTuner.Decision d : r.decisions()) {
            b.append("| ").append(d.ruleId()).append(" | ").append(row(d.asDefined().inSample())).append(" | ").append(row(d.asDefined().outOfSample()))
             .append(" | ").append(d.chosen() == null ? "–" : d.chosen().variant().name()).append(" | ")
             .append(d.chosen() == null ? "– | – | –" : row(d.chosen().inSample())).append(" | ")
             .append(d.chosen() == null ? "– | – | –" : row(d.chosen().outOfSample())).append(" | ")
             .append(d.keep() ? "**keep as warning**" : "demote to info").append(" |\n");
        }
        b.append("\n## Every version tried\n\n");
        for (RuleTuner.Decision d : r.decisions()) {
            b.append("### ").append(d.ruleId()).append(" (").append(d.ruleName()).append(", ").append(d.direction()).append(")\n\n")
             .append(d.reason()).append(".\n\n| Version | In-sample cases | 5 d % | 20 d % | avg 20 d move % | Out-of-sample cases | 5 d % | 20 d % | avg 20 d move % |\n")
             .append("|---|---:|---:|---:|---:|---:|---:|---:|---:|\n");
            for (RuleTuner.Result t : d.tried()) {
                b.append("| ").append(t.variant().name()).append(" | ").append(row(t.inSample())).append(" | ").append(pct(t.inSample().avg20()))
                 .append(" | ").append(row(t.outOfSample())).append(" | ").append(pct(t.outOfSample().avg20())).append(" |\n");
            }
            b.append('\n');
        }
        b.append("## Configuration written\n\n```properties\n");
        RuleTuner.configLines(r).forEach(l -> b.append(l).append('\n'));
        b.append("```\n\nSmall samples are noisy even with this split: treat kept warnings as \"worth a look\", never as predictions.\n");
        return b.toString();
    }
}
